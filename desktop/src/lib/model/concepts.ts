/** Název pojmu v jazyce rozhraní (anglicky = id bez podtržítek). */
export function conceptLabel(id: string, locale: Locale): string {
	if (locale === 'cs' && CS[id]) return CS[id];
	return id.replace(/_/g, ' ');
}

